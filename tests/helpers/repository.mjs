// What the repository-wide scans leave out (imported by the tests that read
// every file of the repository: each fighter's "never named" check, the
// retired names; not a test file itself): what is not the repository's own
// writing.
//
//   - Ignored by Git: Git's store, npm's packages, the generated itch.io
//     release (dist/: copies of files read anyway), the room server's local
//     cache (server/.wrangler/, what `npx wrangler dev` builds and stores)
//     and the native apps' builds (docs/development/native-apps.md: Cargo's
//     and Tauri's output in src-tauri/, Gradle's in android/, and the
//     release and configuration `npx cap sync` copies into the Android app).
//   - Generated by tools and committed: the lockfiles (npm's integrity
//     hashes are random base64, where a name pattern can match by chance,
//     as an archive in dist/ once did) and the binary files the scans'
//     own image pattern does not name (Tauri's .icns icon, Gradle's
//     wrapper .jar).
const NOT_OURS = new Set([
  'src-tauri/target', 'src-tauri/gen',
  'android/.gradle', 'android/build', 'android/app/build', 'android/capacitor-cordova-android-plugins',
  'android/app/src/main/assets/public', 'android/app/src/main/assets/capacitor.config.json',
  'android/app/src/main/assets/capacitor.plugins.json', 'android/app/src/main/res/xml/config.xml',
]);
const NOT_OURS_ANYWHERE = new Set(['.git', 'node_modules', 'dist', '.wrangler', 'package-lock.json', 'Cargo.lock']);
const GENERATED_BINARY = /\.(icns|jar)$/i;

// Whether `path` (relative to the repository, a folder's with or without
// its trailing slash) is left out.
export const notOurs = (path) => {
  const bare = path.replace(/\/$/, '');
  return NOT_OURS.has(bare) || NOT_OURS_ANYWHERE.has(bare.split('/').pop()) || GENERATED_BINARY.test(bare);
};
